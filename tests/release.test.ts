import { describe, expect, it } from "vitest";
import { mkdtempSync, readFileSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
// @ts-expect-error The release helper is a plain ES module script.
import { buildReleaseNotes, extractReleaseNotes, readReleaseVersion } from "../scripts/release.mjs";

const NOTES = [
  "- **Hunk 0.25.0:** the pinned `hunkdiff` dependency moves from 0.23.0 to 0.25.0. (#74)",
  "",
  "Requires Herdr 0.8.0+, Node 22.12+, and npm 10+ or pnpm 10+. Bundles Hunk 0.25.0. Supports macOS, Linux, and Windows; bundled Windows binaries support x64 only.",
].join("\n");

const body = (notes: string) =>
  `Bumps the version to 0.5.1.\n\n## Release notes\n\n${notes}\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_`;

const options = {
  version: "0.5.1",
  hunkVersion: "0.25.0",
  previousTag: "v0.5.0",
  repository: "jhochenbaum/herdr-hunk-diff",
};

describe("release notes", () => {
  it("takes the section up to the footer and appends the changelog link", () => {
    expect(buildReleaseNotes({ ...options, body: body(NOTES) })).toBe(
      `${NOTES}\n\n[Full changelog](https://github.com/jhochenbaum/herdr-hunk-diff/compare/v0.5.0...v0.5.1)\n`,
    );
  });

  it("stops at the next heading and accepts CRLF bodies", () => {
    const text = `## Release notes\r\n\r\n${NOTES.replace(/\n/g, "\r\n")}\r\n\r\n## Testing\r\n\r\nnpm test`;
    expect(extractReleaseNotes(text)).toBe(NOTES);
  });

  it("unwraps a fenced markdown block", () => {
    expect(extractReleaseNotes(body("```markdown\n" + NOTES + "\n```"))).toBe(NOTES);
  });

  it("keeps an existing changelog link", () => {
    const notes = `${NOTES}\n\n[Full changelog](https://example.test)`;
    expect(buildReleaseNotes({ ...options, body: body(notes) })).toBe(`${notes}\n`);
  });

  it("rejects bodies without a release notes section", () => {
    expect(() => buildReleaseNotes({ ...options, body: "Bumps the version." })).toThrow(
      /no "## Release notes" section/,
    );
  });

  it("rejects notes without topic bullets or the requirements line", () => {
    expect(() =>
      buildReleaseNotes({ ...options, body: body("Requires Herdr 0.8.0+. Bundles Hunk 0.25.0.") }),
    ).toThrow(/bullet/);
    expect(() => buildReleaseNotes({ ...options, body: body("- **Fix:** a fix. (#1)") })).toThrow(
      /requirements line/,
    );
  });

  it("rejects a stale bundled Hunk version", () => {
    expect(() =>
      buildReleaseNotes({
        ...options,
        body: body(NOTES.replace("Bundles Hunk 0.25.0", "Bundles Hunk 0.23.0")),
      }),
    ).toThrow(/Hunk 0\.23\.0, but package\.json pins hunkdiff 0\.25\.0/);
  });
});

describe("release version", () => {
  it("matches across the repository manifests", () => {
    const { version } = JSON.parse(readFileSync("package.json", "utf8"));
    expect(readReleaseVersion()).toMatchObject({ version });
  });

  it("reports manifests that disagree", () => {
    const root = mkdtempSync(join(tmpdir(), "release-"));
    writeFileSync(join(root, "package.json"), JSON.stringify({ version: "1.2.0" }));
    writeFileSync(
      join(root, "package-lock.json"),
      JSON.stringify({ version: "1.2.0", packages: { "": { version: "1.2.0" } } }),
    );
    writeFileSync(join(root, "herdr-plugin.toml"), 'version = "1.1.0"\n');
    expect(() => readReleaseVersion(root)).toThrow(/herdr-plugin\.toml has 1\.1\.0/);
  });
});
